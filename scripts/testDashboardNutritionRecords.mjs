import { buildSharedNutritionSummary, sortSharedNutrition } from "../src/utils/sharedNutritionSummary.js";
import assert from 'node:assert/strict';
import fs from 'node:fs';
const source = fs.readFileSync('src/components/Clientdashboard.jsx', 'utf8');
const start = source.indexOf('      const nutritionByDossier = new Map();');
const end = source.indexOf('      // ✅ sessions', start);
const callbacks = new Map();
const state = {summary:null,stopped:[]};
const names = ['buildSharedNutritionSummary','sortSharedNutrition','dossierIds','onSnapshot','query','collection','where','orderBy','limit','db','toMillis','setNutritionSummary','setDashboardNutritionMealKeys','setNutritionMealHabits','inferNutritionMealHabits'];
const run = new Function(...names, `let active=true, unsubNutrition, unsubNutritionLogs; ${source.slice(start,end)}; return () => {active=false; unsubNutrition?.(); unsubNutritionLogs?.();};`);
const stop = run(buildSharedNutritionSummary,sortSharedNutrition,['club','personal'], (path, success, failure)=>{callbacks.set(path,{success,failure});return ()=>state.stopped.push(path);}, x=>x, (_,__,id,name)=>`${id}/${name}`, ()=>null, ()=>null, ()=>null, {}, date=>Date.parse(date)||0, value=>state.summary=value, ()=>{}, value=>state.habits=value, x=>x);
const snap = (date, enabled=true) => ({docs:[{id:'assessment',data:()=>({clientShare:{enabled,sections:{summary:true},sharedAt:date},computed:{kcalTarget:2100}})}]});
callbacks.get('club/nutrition_assessments').success({docs:[]});
assert.equal(state.summary,null);
callbacks.get('personal/nutrition_assessments').success(snap('2026-10-27'));
assert.equal(state.summary.sourceClientId,'personal');
assert.equal(state.summary.kcal,2100);
assert.ok(callbacks.has('personal/nutrition_daily_logs'));
assert.equal(callbacks.has('club/nutrition_daily_logs'),false);
callbacks.get('club/nutrition_assessments').success(snap('2026-10-28'));
assert.equal(state.summary.sourceClientId,'club');
assert.equal(state.summary.sharedCount,2);
assert.ok(state.stopped.includes('personal/nutrition_daily_logs'));
callbacks.get('club/nutrition_assessments').success(snap('2026-10-28',false));
assert.equal(state.summary.sourceClientId,'personal');
stop();
assert.ok(state.stopped.includes('club/nutrition_assessments'));
assert.ok(state.stopped.includes('personal/nutrition_assessments'));
console.log('Dashboard nutrition: secondary dossier, latest share, journal routing, revocation and cleanup OK.');
