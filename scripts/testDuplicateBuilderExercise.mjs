import assert from 'node:assert/strict';
import { duplicateBuilderExercise } from '../src/utils/duplicateBuilderExercise.js';
let sequence = 0;
const exercise = { id: 'original', exerciseId: 'catalog-squat', 'Séries': 2, 'Répétitions': 6, 'Charge (kg)': 95, 'Repos (min:sec)': 90, notes: 'Tempo lent', notesEnabled: true, useAdvancedSets: true, optionsOrder: ['Charge (kg)', 'Répétitions'], sets: [{ _id: 's1', chargeKg: 95, reps: 6 }, { _id: 's2', chargeKg: 90, reps: 8 }], extra: { tempo: [3, 1, 1] }, linkNext: true };
const next = { id: 'next' };
const list = [exercise, next];
const result = duplicateBuilderExercise(list, 0, () => `copy-${++sequence}`);
assert.equal(result.length, 3);
assert.equal(result[0], exercise);
assert.equal(result[2], next);
assert.equal(list.length, 2);
const copy = result[1];
assert.notEqual(copy.id, exercise.id);
assert.notEqual(copy.sets[0]._id, exercise.sets[0]._id);
const prescription = value => ({ ...value, id: null, sets: value.sets.map(set => ({ ...set, _id: null })) });
assert.deepEqual(prescription(copy), prescription(exercise));
copy.sets[0].chargeKg = 10;
copy.extra.tempo[0] = 9;
copy.optionsOrder.reverse();
assert.equal(exercise.sets[0].chargeKg, 95);
assert.equal(exercise.extra.tempo[0], 3);
assert.equal(exercise.optionsOrder[0], 'Charge (kg)');
assert.equal(duplicateBuilderExercise(list, 99, () => 'unused'), list);
assert.equal(duplicateBuilderExercise([next], 0, () => 'last').length, 2);
console.log('PASS: inserted immediately after original; complete prescription retained; nested edits independent; unique IDs and end-of-list supported.');
