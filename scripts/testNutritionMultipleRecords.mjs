import { sortSharedNutrition } from "../src/utils/sharedNutritionSummary.js";
import assert from 'node:assert/strict';
import fs from 'node:fs';
const source = fs.readFileSync('src/components/ClientNutritionSharedSection.jsx', 'utf8');
const start = source.indexOf('    const sourceIds = JSON.parse(sourceIdsKey);');
const end = source.indexOf('\n  }, [sourceIdsKey, loadAttempt]);', start);
const callbacks = new Map();
let rows = [], selected = '', loading, error, stopped = 0;
const run = new Function('sortSharedNutrition', 'sourceIdsKey', 'setLoading', 'setLoadError', 'setAssessments', 'setSelectedAssessmentId', 'onSnapshot', 'query', 'collection', 'where', 'db', source.slice(start, end));
const cleanup = run(sortSharedNutrition, JSON.stringify(['club', 'personal']), v => loading = v, v => error = v, v => rows = v, fn => selected = fn(selected), (id, success, failure) => {callbacks.set(id, {success, failure}); return () => stopped++;}, ref => ref, (_, __, id) => id, () => null, {});
const snapshot = (enabled, sections, date) => ({docs:[{id:'same-id',data:()=>({clientShare:{enabled,sections,sharedAt:date}})}]});
callbacks.get('club').success({docs:[]});
assert.equal(loading, true, 'Wait for all linked records before concluding empty');
callbacks.get('personal').success(snapshot(true, {summary:true}, '2026-10-27'));
assert.equal(rows.length, 1);
assert.equal(rows[0].sourceClientId, 'personal');
assert.equal(rows[0].id, 'same-id', 'Preserve original assessment ID for journal writes');
assert.equal(selected, 'personal/same-id');
assert.equal(loading, false);
callbacks.get('club').success(snapshot(true, {ration:true}, '2026-10-26'));
assert.equal(new Set(rows.map(row=>row.shareKey)).size, 2, 'Same assessment IDs in separate dossiers remain distinct');
assert.equal(selected, 'personal/same-id', 'Keep selection when another record updates');
callbacks.get('personal').success(snapshot(false, {summary:true}, '2026-10-27'));
assert.equal(rows.length, 1, 'Revoked shares disappear');
assert.equal(selected, 'club/same-id');
cleanup();
assert.equal(stopped,2);
callbacks.get('club').success({docs:[]});
assert.equal(rows.length,1,'Ignore callbacks after unmount');
assert.equal(error,false);
console.log('Nutrition: multiple dossiers, delayed loading, selection, revocation and cleanup OK.');
