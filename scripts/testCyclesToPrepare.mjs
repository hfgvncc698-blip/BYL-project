import assert from 'node:assert/strict';
import {cyclesToPrepare} from '../src/utils/cyclesToPrepare.js';
const now=new Date('2026-10-21T12:00:00');
const program=(id,done=0)=>({id,_total:4,_done:done,activeWeeks:1,assignedAt:'2026-10-15T12:00:00',nomProgramme:id});
const client=(id,start,done=0)=>({id,prenom:id,trainingPlan:{start,cycles:[{id:'one',programId:'p',weeks:1},{id:'two',weeks:4}]},programmesAssignes:[program('p',done)]});
assert.equal(cyclesToPrepare([client('completed','2026-10-01',4)],now)[0].finished,true);
assert.equal(cyclesToPrepare([client('today','2026-10-15')],now)[0].days,0);
assert.equal(cyclesToPrepare([client('seven','2026-10-22')],now)[0].days,7);
assert.equal(cyclesToPrepare([client('eight','2026-10-23')],now).length,0);
const ready=client('ready','2026-10-15',4); ready.trainingPlan.cycles[1].programId='next';ready.programmesAssignes.push(program('next'));
assert.equal(cyclesToPrepare([ready],now).length,0);
ready.programmesAssignes[1].status='draft';assert.equal(cyclesToPrepare([ready],now).length,1);
const closed=client('closed','2026-10-01',4);closed.trainingPlan.cycles[0].closedAt='2026-10-07';
assert.equal(cyclesToPrepare([closed],now)[0].finished,true);
const separate=client('separate','2026-10-15',4);separate.sportFollowView='programs';assert.equal(cyclesToPrepare([separate],now).length,0);
assert.equal(cyclesToPrepare([{id:'empty',programmesAssignes:[]}],now)[0].noCycle,true);
assert.equal(cyclesToPrepare([{id:'empty-plan',trainingPlan:{cycles:[]}}],now)[0].noCycle,true);
assert.equal(cyclesToPrepare([{id:'draft-only',programmesAssignes:[{...program('draft'),status:'draft'}]}],now)[0].noCycle,true);
assert.deepEqual(cyclesToPrepare([client('soon','2026-10-20'),client('done','2026-10-01',4)],now).map(r=>r.clientId),['done','soon']);
assert.equal(cyclesToPrepare([{id:'legacy',programmesAssignes:[program('p',4)]}],now).length,1);
console.log('Cycles to prepare: completion, 0/7-day boundaries, draft/ready successors, closed cycles, legacy and exclusions passed.');
