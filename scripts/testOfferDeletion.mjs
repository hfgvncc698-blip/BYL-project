import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const encode=source=>`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`;
const schedule=encode(readFileSync(new URL('../src/utils/coachOfferSchedule.js',import.meta.url),'utf8'));
const source=readFileSync(new URL('../src/utils/offerDeletion.js',import.meta.url),'utf8').replace("'./coachOfferSchedule'",JSON.stringify(schedule));
const {activeOfferContracts}=await import(encode(source));
const offer={id:'offer',name:'Pack',type:'pack'};
const contract={offerId:'offer',name:'Old name',type:'pack',quantity:10,remaining:4,start:'2026-01-01',months:0};
const active=(c,o=offer)=>activeOfferContracts(o,[c],'2026-10-14').length;
assert.equal(active(contract),1);
assert.equal(active({...contract,remaining:0}),0);
assert.equal(active({...contract,months:6}),0);
assert.equal(active({...contract,expiresAt:'2026-10-14'}),1);
assert.equal(active({...contract,offerId:'other',name:'Pack'}),0);
assert.equal(active({...contract,type:'recurring',end:'2026-10-14'}),1);
assert.equal(active({...contract,type:'recurring',end:'2026-10-13'}),0);
assert.equal(active({...contract,type:'recurring',start:'2027-01-01',end:'2027-12-31'}),1);
assert.equal(active({...contract,status:'ended'}),0);
assert.equal(active({...contract,remaining:undefined,completedSessions:10}),0);
assert.equal(active({...contract,remaining:undefined}),1);
assert.equal(active({...contract,offerId:undefined,name:'Pack'}),1);
assert.equal(active({...contract,offerId:undefined,titleKey:'samplePack'}, {...offer,titleKey:'samplePack'}),1);
console.log('Catalogue deletion: active, future, expired, completed and legacy assignments checked');
