const assert=require('node:assert/strict');
const {calculateCoachCredits,creditPeriod}=require('../backend/utils/coachOfferCredits');
const now=Date.parse('2026-10-14T12:00:00Z');
const pack={id:'pack',clientId:'client',name:'Pack',type:'pack',service:'coaching',quantity:2,start:'2026-10-01',expiresAt:'2027-04-01',createdAt:'2026-10-01'};
const event=(id,status='à venir',extra={})=>({id,clientId:'client',coachId:'coach',visibility:'both',status,start:Date.parse(status==='à venir'?'2026-10-20T10:00:00Z':'2026-10-10T10:00:00Z'),...extra});
const run=(events,contracts=[pack])=>calculateCoachCredits(contracts,events,'coach',now);
let result=run([event('one','validée'),event('future')]);
assert.equal(result.contracts[0].remaining,1);assert.equal(result.contracts[0].reserved,1);assert.equal(result.contracts[0].available,0);
assert.deepEqual(run([event('one','validée'),event('one','validée')]),run([event('one','validée')]));
assert.equal(run([event('cancelled','annulée')]).contracts[0].used,0);
assert.equal(run([event('missed','manquée')]).contracts[0].used,1);
assert.equal(run([event('missed','manquée')]).contracts[0].completedSessions,0);
assert.equal(run([event('missed','manquée',{excuseDecision:'accepted'})]).contracts[0].used,0);
assert.equal(run([event('own','validée',{visibility:'client'})]).contracts[0].used,0);
assert.equal(run([event('other','validée',{coachId:'other'})]).contracts[0].used,0);
assert.equal(run([event('club','validée',{clubId:'club'})]).contracts[0].used,0);
assert.equal(run([event('nutrition','validée',{eventType:'nutrition_appointment'})]).contracts[0].used,0);
assert.equal(run([event('old','validée',{start:Date.parse('2026-09-30')})]).contracts[0].used,0);
assert.equal(run([event('future','à venir',{start:Date.parse('2027-05-01')})]).contracts[0].reserved,0);
assert.equal(run([event('future-validated','validée',{start:now+86400000})]).contracts[0].reserved,1);
const earlier={...pack,id:'early',quantity:1,expiresAt:'2026-11-01'};
result=run([event('a','validée'),event('b','validée'),event('c','validée'),event('d','validée')],[pack,earlier]);
assert.equal(result.contracts.find(c=>c.id==='early').used,1);assert.equal(result.contracts.find(c=>c.id==='pack').used,2);assert.equal(result.uncovered.length,1);
const sub={...pack,id:'monthly',type:'recurring',paymentDay:1,end:'2027-09-30',expiresAt:'2027-09-30'};
result=run([event('sept','validée',{start:Date.parse('2026-09-10')}),event('oct','validée'),event('nov','à venir',{start:Date.parse('2026-11-10')})],[sub]);
assert.equal(result.contracts[0].remaining,1);assert.equal(result.contracts[0].reserved,0);
assert.equal(result.contracts[0].history.find(e=>e.id==='nov').period,'2026-11-01');
assert.equal(creditPeriod({...sub,start:'2028-01-31',end:'2028-05-31',expiresAt:'2028-05-31',paymentDay:31},'2028-02-29').key,'2028-02-29');
// Rescheduling a canonical event moves its reservation, without a second debit.
const moved=event('move','à venir',{start:Date.parse('2026-11-10')});
result=run([moved],[sub]);
assert.equal(result.contracts[0].reserved,0);
assert.equal(result.contracts[0].history.length,1);
assert.equal(result.contracts[0].history[0].period,'2026-11-01');
assert.equal(run([{...moved,clientId:'another-client'}],[sub]).contracts[0].history.length,0);
assert.equal(run([{...moved,status:'annulée'}],[sub]).contracts[0].history.length,0);
// An expired pack must still show sessions already consumed.
result=run([event('past','validée')],[{...pack,expiresAt:'2026-10-12'}]);
assert.equal(result.contracts[0].state,'expired');
assert.equal(result.contracts[0].used,1);
assert.equal(result.contracts[0].remaining,0);
assert.equal(result.contracts[0].available,0);
assert.equal(result.contracts[0].completedSessions,1);
result=run([event('outside','validée',{creditMode:'outside'})]);
assert.equal(result.contracts[0].used,0);assert.equal(result.uncovered.length,1);assert.equal(result.timeline[0].credit,'outside');
result=run([event('cancel','annulée',{coachContractId:'pack'})]);
assert.equal(result.timeline[0].credit,'released');assert.equal(result.timeline[0].contractId,'pack');
result=run([event('reserved','à venir',{coachContractId:'pack'})],[pack,earlier]);
assert.equal(result.contracts.find(c=>c.id==='pack').reserved,1);assert.equal(result.contracts.find(c=>c.id==='early').reserved,0);
result=run([event('before','validée',{start:Date.parse('2026-10-05')}),event('after','validée',{start:Date.parse('2026-10-12')})],[{...pack,quantity:10,openingUsed:4,openingBalanceAt:'2026-10-10'}]);
assert.equal(result.contracts[0].used,5);assert.equal(result.contracts[0].remaining,5);assert.equal(result.contracts[0].history.length,1);
console.log('Coach credits: reservation, completion, absence, cancellation, FIFO, monthly reset, scope and deduplication passed');
