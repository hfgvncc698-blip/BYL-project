import assert from 'node:assert/strict';
import { createRationSaver } from '../src/utils/rationSave.js';
import { waitForNutritionOperation } from '../src/utils/nutritionLoading.js';
let release;
const writes = [];
const save = createRationSaver(payload => { writes.push(payload); return new Promise(resolve => { release = resolve; }); });
const original = save({quantity:1}, 'first');
await assert.rejects(waitForNutritionOperation(original, 5), {code:'nutrition-confirmation-timeout'});
const retry = save({quantity:1}, 'first');
assert.equal(writes.length,1);
release();
await Promise.all([original,retry]);
await save({quantity:1}, 'first');
assert.equal(writes.length,1);
const second = save({quantity:2}, 'second');
await Promise.resolve();
assert.equal(writes.length,2);
release(); await second;
let attempts=0;
const denied = createRationSaver(async () => { if (++attempts === 1) throw new Error('permission-denied'); });
await assert.rejects(denied({},'retry'),/permission-denied/);
await denied({},'retry');
assert.equal(attempts,2);
let finish;
const queueWrites=[];
const serial = createRationSaver(payload => { queueWrites.push(payload); return new Promise(resolve => { finish=resolve; }); });
const old = serial('old','old');
const latest = serial('latest','latest');
await Promise.resolve();
assert.deepEqual(queueWrites,['old']);
finish(); await old;
await Promise.resolve();
assert.deepEqual(queueWrites,['old','latest']);
finish(); await latest;
console.log('Ration save OK: timeout releases UI, retry reuses write, rejection allows retry, edits serialize.');
