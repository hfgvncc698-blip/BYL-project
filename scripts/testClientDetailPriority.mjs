import assert from 'node:assert/strict';
import { createDashboardReadPool } from '../src/utils/coachDashboardLoading.js';
const pool = createDashboardReadPool(1);
const order = [];
let release;
const first = pool.run(() => new Promise(resolve => { release = resolve; }));
await Promise.resolve();
const roots = ['B', 'C'].map(id => pool.run(async () => { order.push(id); return id; }));
const details = ['A1', 'A2'].map(id => pool.run(async () => { order.push(id); return id; }, {priority:1}));
release();
await Promise.all([first, ...roots, ...details]);
assert.deepEqual(order, ['A1','A2','B','C'], 'finish already-loading rows before queued client roots, FIFO within each priority');
assert.equal(pool.stats.peak, 1, 'priority must respect the shared read budget');
const failure = pool.run(() => { throw new Error('network'); }, {priority:1});
await assert.rejects(failure, /network/);
assert.equal(await pool.run(() => 'recovered'), 'recovered');
console.log('Client details priority: bounded reads, stable order, queued roots preserved and failure recovery OK');

const { mergeDashboardClientProgress } = await import('../src/utils/coachDashboardLoading.js');
const oldRows = [{id:'A',_lastCoachInteractionMs:12,programmesAssignes:[{id:'P',sessionsEffectuees:[{id:'coach'}],_coachNextIndex:1}]},{id:'B'}];
const freshHistory = [{id:'coach'},{id:'legacy'}];
const updated = mergeDashboardClientProgress(oldRows,{id:'A',programmesAssignes:[{id:'P',sessionsEffectuees:freshHistory,_done:2}]});
assert.equal(updated[0].programmesAssignes[0]._done,2);
assert.equal(updated[0].programmesAssignes[0]._progressSessionsEffectuees,freshHistory);
assert.equal(updated[0].programmesAssignes[0].sessionsEffectuees.length,1,'do not broaden calendar activity scope during progress refresh');
assert.equal(updated[0]._lastCoachInteractionMs,12);
assert.equal(updated[1],oldRows[1]);
assert.equal(oldRows[0].programmesAssignes[0]._done,undefined,'no cache mutation');
console.log('Recent-client progress updates independently without broadening activity scope: OK');
