import assert from 'node:assert/strict';
import { microTargetKeyFromNutrient, prettyMicroNutrient, targetForMicroNutrient } from '../src/utils/rationMicroTargets.js';
import { computeMicronutrientTargets } from '../src/utils/nutritionContext.js';
const targets = computeMicronutrientTargets({ inputs: { age: 29, sexe: 'homme' } });
assert.equal(microTargetKeyFromNutrient('vitamine_b12_g_100g'), 'vitB12');
assert.equal(targetForMicroNutrient('vitamine_b12_g_100g', targets).value, 4);
assert.equal(microTargetKeyFromNutrient('selenium_g_100g'), 'selenium');
assert.equal(targetForMicroNutrient('selenium_g_100g', targets).value, 70);
assert.equal(targetForMicroNutrient('sel_chlorure_de_sodium_g_100g', targets).value, 5);
assert.equal(targetForMicroNutrient('sel_chlorure_de_sodium_g_100g', targets).unit, 'g');
assert.equal(targetForMicroNutrient('activite_vitaminique_a_equivalents_retinol_g_100g', targets).value, targets.vitA.value);
assert.equal(targetForMicroNutrient('ag_12_0_laurique_g_100g', targets), undefined);
assert.equal(prettyMicroNutrient('iode_g_100g'), 'iode µg');
assert.equal(prettyMicroNutrient('glucides_g_100g'), 'glucides g');
assert.equal(targets.cuivre.value, 1.6);
assert.equal(targets.zinc.direction, 'review');
assert.equal(computeMicronutrientTargets({ inputs: { age: 12 } }).iode.direction, 'review');
assert.equal(computeMicronutrientTargets({ inputs: {} }).iode.direction, 'review');
console.log('Micronutrient targets OK: B12, selenium, salt conversion, units, unsupported nutrients and adult scope.');
