const assert=require('node:assert/strict'),fs=require('node:fs'),{randomBytes}=require('node:crypto'),{gzipSync}=require('node:zlib');
const {encode}=require('../backend/utils/coachPageWire');
const {shareDashboardText}=require('../audits/dashboard-shared-text/experiment/dashboardSharedText.cjs');
const source=fs.readFileSync('audits/dashboard-shared-text/experiment/coachProgramBatch.js','utf8').replace(/^import .*;\n/gm,'').replace(/export function /g,'function ');
const decode=new Function(source+';return decode;')();
const image=randomBytes(96*1024).toString('base64');
const program={sessions:[{name:'Synthetic',exercises:[{image,description:image,sets:[{reps:12,weight:42}],unknownLegacy:{text:image}}]}],custom:{__bylWire:['shared-text',0]},extra:'keep'};
const payload={clients:{synthetic:Array.from({length:20},(_,i)=>({id:'p'+i,data:encode(program),history:[{id:'h',data:encode({status:'completed',note:image})}]}))}};
const packed=shareDashboardText(payload);
assert.deepEqual(decode(packed.clients,packed.sharedText),decode(payload.clients));
assert(packed.sharedText.length>0);
const unique={clients:{unique:[{id:'p',data:encode({text:image}),history:[]}]}};assert.deepEqual(decode(shareDashboardText(unique).clients,shareDashboardText(unique).sharedText),decode(unique.clients));
assert.throws(()=>decode({__bylWire:['shared-text',9]},['x']),/Invalid/);
assert.throws(()=>decode({__bylWire:['shared-text',-1]},['x']),/Invalid/);
assert.throws(()=>decode({__bylWire:['shared-text',0]},[{}]),/Invalid/);
const before=Buffer.byteLength(JSON.stringify(payload)),after=Buffer.byteLength(JSON.stringify(packed));
const beforeGzip=gzipSync(JSON.stringify(payload)).length,afterGzip=gzipSync(JSON.stringify(packed)).length;
assert(after<before/10);assert(afterGzip<beforeGzip/10);
console.log(JSON.stringify({passed:true,before,after,beforeGzip,afterGzip,note:'Synthetic repetition, not real-page performance'}));
